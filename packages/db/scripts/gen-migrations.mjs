// Bundles migrations/*.sql into src/migrations.generated.ts (RN can't read files at runtime).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'migrations');
const out = join(root, 'src', 'migrations.generated.ts');
const files = readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const entries = files.map((f, i) => {
  const version = Number(f.slice(0, 4));
  if (version !== i + 1) throw new Error(`migration ${f} breaks the 1..n sequence`);
  return `  { version: ${version}, name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))} },`;
});
const body = `// GENERATED by scripts/gen-migrations.mjs — edit migrations/*.sql instead.\nimport type { Migration } from './migrate';\n\nexport const MIGRATIONS: readonly Migration[] = [\n${entries.join('\n')}\n];\n`;
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== body) {
    console.error('src/migrations.generated.ts is stale — run `pnpm --filter @dukaan/db gen`');
    process.exit(1);
  }
} else {
  writeFileSync(out, body);
  console.log(`wrote ${files.length} migration(s)`);
}
